/*
 * Computes the (2*l1+1) x (2*l2+1) Slater-Koster hopping matrix block for
 * the bond vector (x,y,z) (need not be normalized -- only its direction
 * matters) and hopping parameters params[0..min(l1,l2)] = {sigma, pi, delta,
 * phi}. l1, l2 must each be in [0,4]; out-of-range checking is left to the
 * Lua binding layer.
 *
 * H is filled in as a real CompactMatrixType: H->QComplex, H->Ni, H->Nj are
 * set here and InitCompactMatrix(H) is called to allocate H->VRe (flat
 * row-major, H->VRe[i*H->Nj+j]); all other CompactMatrixType fields are left
 * at whatever InitCompactMatrix sets them to.
 */
int SlaterKosterTable(int l1, int l2, double x, double y, double z, double const *params, CompactMatrixType *H)
{
  H->QComplex = 0;
  H->Ni = (uint32_t)(2*l1+1);
  H->Nj = (uint32_t)(2*l2+1);
  if (InitCompactMatrix(H))
  {
    printf("InitCompactMatrix(H) failed in SlaterKosterBlock\n");
    return 1;
  }
  if (l1 <= l2) {
    switch (l1*10+l2) {
      case 0: SKBlock_00(x,y,z,params[0],H->VRe); return 0;
      case 1: SKBlock_01(x,y,z,params[0],H->VRe); return 0;
      case 11: SKBlock_11(x,y,z,params[0], params[1],H->VRe); return 0;
      case 2: SKBlock_02(x,y,z,params[0],H->VRe); return 0;
      case 12: SKBlock_12(x,y,z,params[0], params[1],H->VRe); return 0;
      case 22: SKBlock_22(x,y,z,params[0], params[1], params[2],H->VRe); return 0;
      case 3: SKBlock_03(x,y,z,params[0],H->VRe); return 0;
      case 13: SKBlock_13(x,y,z,params[0], params[1],H->VRe); return 0;
      case 23: SKBlock_23(x,y,z,params[0], params[1], params[2],H->VRe); return 0;
      case 33: SKBlock_33(x,y,z,params[0], params[1], params[2], params[3],H->VRe); return 0;
      case 4: SKBlock_04(x,y,z,params[0],H->VRe); return 0;
      case 14: SKBlock_14(x,y,z,params[0], params[1],H->VRe); return 0;
      case 24: SKBlock_24(x,y,z,params[0], params[1], params[2],H->VRe); return 0;
      case 34: SKBlock_34(x,y,z,params[0], params[1], params[2], params[3],H->VRe); return 0;
      case 44: SKBlock_44(x,y,z,params[0], params[1], params[2], params[3], params[4],H->VRe); return 0;
      default: return 1;
    }
  }
  else
  {
    /* l1 > l2: use T(l1,l2)(n) = (-1)^(l1+l2) * T(l2,l1)(n)^T */
    double Htmp[81];
    int n1 = 2*l1+1, n2 = 2*l2+1;
    double sign = ((l1+l2)%2==0) ? 1.0 : -1.0;
    switch (l2*10+l1) {
      case 0: SKBlock_00(x,y,z,params[0],Htmp); break;
      case 1: SKBlock_01(x,y,z,params[0],Htmp); break;
      case 11: SKBlock_11(x,y,z,params[0], params[1],Htmp); break;
      case 2: SKBlock_02(x,y,z,params[0],Htmp); break;
      case 12: SKBlock_12(x,y,z,params[0], params[1],Htmp); break;
      case 22: SKBlock_22(x,y,z,params[0], params[1], params[2],Htmp); break;
      case 3: SKBlock_03(x,y,z,params[0],Htmp); break;
      case 13: SKBlock_13(x,y,z,params[0], params[1],Htmp); break;
      case 23: SKBlock_23(x,y,z,params[0], params[1], params[2],Htmp); break;
      case 33: SKBlock_33(x,y,z,params[0], params[1], params[2], params[3],Htmp); break;
      case 4: SKBlock_04(x,y,z,params[0],Htmp); break;
      case 14: SKBlock_14(x,y,z,params[0], params[1],Htmp); break;
      case 24: SKBlock_24(x,y,z,params[0], params[1], params[2],Htmp); break;
      case 34: SKBlock_34(x,y,z,params[0], params[1], params[2], params[3],Htmp); break;
      case 44: SKBlock_44(x,y,z,params[0], params[1], params[2], params[3], params[4],Htmp); break;
      default: return 1;
    }
    /* Htmp is (n2 x n1); transpose into H->VRe (n1 x n2) with sign */
    {
      int i,j;
      for (i=0;i<n1;i++)
      {
        for (j=0;j<n2;j++)
        {
          H->VRe[i*n2+j] = sign*Htmp[j*n1+i];
        }
      }
    }
  }
  return 0;
}
