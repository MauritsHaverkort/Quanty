/*
 * SlaterKoster.cpp -General two-center Slater-Koster hopping matrix blocks
 * for s, p, d, f, g orbitals (l = 0..4), for an arbitrary bond vector (x,y,z).
 *
 * ORBITAL ORDERING (Quanty "Kubic harmonics" convention, matching
 * https://www.quanty.org/physics_chemistry/orbitals/k ; for s,p this is the
 * same as the tesseral order, for d it is a reordering of the
 * tesseral order, and for f, g it is a genuinely different real basis --
 * see NORMALIZATION note below):
 *   l=0 (s):  [ s ]
 *   l=1 (p):  [ px, py, pz ]
 *   l=2 (d):  [ dx2-y2, dz2, dyz, dxz, dxy ]
 *   l=3 (f):  [ a2u, t1u_x, t1u_y, t1u_z, t2u_x, t2u_y, t2u_z ]
 *             (cubic/kubic harmonics: a2u ~ xyz; t1u_x ~ x(2x^2-3y^2-3z^2)
 *             and cyclic; t2u_x ~ x(y^2-z^2) and cyclic -- these are the
 *             a2u + t1u + t2u irreducible combinations of the l=3 spherical
 *             harmonics under the cubic (Oh) point group)
 *   l=4 (g):  [ a1g, eg_v, eg_u, t1g_yz, t1g_zx, t1g_xy, t2g_yz, t2g_zx, t2g_xy ]
 *             (cubic/kubic harmonics:
 *             a1g ~ x^4-3x^2(y^2+z^2)+y^4-3y^2z^2+z^4 (totally symmetric);
 *             eg_v ~ (x^2-y^2)(x^2+y^2-6z^2), eg_u ~ x^4+y^4-2z^4+6z^2(x^2+y^2)-12x^2y^2
 *             (the two Eg partners, "v"=x2-y2-like, "u"=z-like, in analogy
 *             to dx2-y2/dz2); t1g_yz ~ yz(y^2-z^2) and cyclic (zx,xy);
 *             t2g_yz ~ yz(6x^2-y^2-z^2) and cyclic (zx,xy). These are the
 *             a1g + eg + t1g + t2g irreducible combinations of the l=4
 *             spherical harmonics under Oh.
 *
 * NORMALIZATION: all orbitals are normalized real kubic harmonics such that,
 * for a bond exactly along +z, the "sigma"-type orbital of each l evaluates
 * to exactly 1 (e.g. pz, dz2, t1u_z). This pattern of a SINGLE basis member
 * carrying all the "polar" weight is a coincidence of low l -- for g (l=4)
 * under the cubic (Oh) group it genuinely does NOT hold: the totally
 * polar (z-axis-invariant) direction decomposes as a MIXTURE of a1g and
 * eg_u only (never t1g or t2g, by symmetry). Concretely, for a bond along
 * +z, ggSigma alone gives H[a1g,a1g] = 7/12, H[eg_u,eg_u] = 5/12,
 * H[a1g,eg_u] = -sqrt(35)/12, and all other entries 0 -- there is no single
 * g orbital analogous to pz/dz2/t1u_z. This was verified directly (see
 * DERIVATION notes) and is a real feature of the l=4 cubic decomposition,
 * not a bug.
 *
 * PARAMETERS per (l1,l2) pair, params[0..min(l1,l2)] = {sigma, pi, delta, phi, gamma}:
 *   (0,0): {ssSigma}                                1 param
 *   (0,1): {spSigma}                                1 param
 *   (0,2): {sdSigma}                                1 param
 *   (0,3): {sfSigma}                                1 param
 *   (0,4): {sgSigma}                                1 param
 *   (1,1): {ppSigma, ppPi}                          2 params
 *   (1,2): {pdSigma, pdPi}                          2 params
 *   (1,3): {pfSigma, pfPi}                          2 params
 *   (1,4): {pgSigma, pgPi}                          2 params
 *   (2,2): {ddSigma, ddPi, ddDelta}                 3 params
 *   (2,3): {dfSigma, dfPi, dfDelta}                 3 params
 *   (2,4): {dgSigma, dgPi, dgDelta}                 3 params
 *   (3,3): {ffSigma, ffPi, ffDelta, ffPhi}          4 params
 *   (3,4): {fgSigma, fgPi, fgDelta, fgPhi}          4 params
 *   (4,4): {ggSigma, ggPi, ggDelta, ggPhi, ggGamma} 5 params
 * For l1 > l2, pass the SAME canonical parameter set (sigma,pi,...) -- the
 * function handles the reordering and sign internally.
 *
 */

/* l1=0, l2=0: H is a flat row-major (1 x 1) array, H[i*1+j] */
static void SKBlock_00(double x, double y, double z, double ssSigma, double *H)
{
  H[0] = ssSigma;
}

/* l1=0, l2=1: H is a flat row-major (1 x 3) array, H[i*3+j] */
static void SKBlock_01(double x, double y, double z, double spSigma, double *H)
{
  double t0 = spSigma/sqrt(pow(x, 2) + pow(y, 2) + pow(z, 2));
  H[0] = t0*x;
  H[1] = t0*y;
  H[2] = t0*z;
}

/* l1=0, l2=2: H is a flat row-major (1 x 5) array, H[i*5+j] */
static void SKBlock_02(double x, double y, double z, double sdSigma, double *H)
{
  double t0 = sqrt(3);
  double t1 = pow(x, 2);
  double t2 = pow(y, 2);
  double t3 = pow(z, 2);
  double t4 = t1 + t2;
  double t5 = sdSigma/(t3 + t4);
  double t6 = (1.0/2.0)*t5;
  double t7 = t0*t5*z;
  H[0] = t0*t6*(t1 - t2);
  H[1] = t6*(2*t3 - t4);
  H[2] = t7*y;
  H[3] = t7*x;
  H[4] = t0*t5*x*y;
}

/* l1=0, l2=3: H is a flat row-major (1 x 7) array, H[i*7+j] */
static void SKBlock_03(double x, double y, double z, double sfSigma, double *H)
{
  double t0 = sqrt(15);
  double t1 = pow(x, 2);
  double t2 = pow(y, 2);
  double t3 = pow(z, 2);
  double t4 = pow(t1 + t2 + t3, -3.0/2.0);
  double t5 = 3*t2;
  double t6 = 3*t3;
  double t7 = (1.0/2.0)*sfSigma*t4;
  double t8 = t7*x;
  double t9 = 3*t1;
  double t10 = t7*y;
  double t11 = t7*z;
  double t12 = -t3;
  H[0] = sfSigma*t0*t4*x*y*z;
  H[1] = t8*(2*t1 - t5 - t6);
  H[2] = t10*(2*t2 - t6 - t9);
  H[3] = t11*(2*t3 - t5 - t9);
  H[4] = t0*t8*(t12 + t2);
  H[5] = t0*t10*(-t1 - t12);
  H[6] = t0*t11*(t1 - t2);
}

/* l1=1, l2=1: H is a flat row-major (3 x 3) array, H[i*3+j] */
static void SKBlock_11(double x, double y, double z, double ppSigma, double ppPi, double *H)
{
  double t0 = pow(x, 2);
  double t1 = pow(y, 2);
  double t2 = pow(z, 2);
  double t3 = 1.0/(t0 + t1 + t2);
  double t4 = t0*t3;
  double t5 = t3*x;
  double t6 = -ppPi*t5*y + ppSigma*t3*x*y;
  double t7 = -ppPi*t5*z + ppSigma*t3*x*z;
  double t8 = t1*t3;
  double t9 = -ppPi*t3*y*z + ppSigma*t3*y*z;
  double t10 = t2*t3;
  H[0] = ppPi*(1 - t4) + ppSigma*t4;
  H[1] = t6;
  H[2] = t7;
  H[3] = t6;
  H[4] = ppPi*(1 - t8) + ppSigma*t8;
  H[5] = t9;
  H[6] = t7;
  H[7] = t9;
  H[8] = ppPi*(1 - t10) + ppSigma*t10;
}

/* l1=1, l2=2: H is a flat row-major (3 x 5) array, H[i*5+j] */
static void SKBlock_12(double x, double y, double z, double pdSigma, double pdPi, double *H)
{
  double t0 = pow(z, 2);
  double t1 = pow(y, 2);
  double t2 = 2*pdPi;
  double t3 = pow(x, 2);
  double t4 = -t1 + t3;
  double t5 = sqrt(3);
  double t6 = pdSigma*t5;
  double t7 = t1 + t3;
  double t8 = pow(t0 + t7, -3.0/2.0);
  double t9 = (1.0/2.0)*t8;
  double t10 = t9*x;
  double t11 = 2*t0;
  double t12 = pdSigma*(-t11 + t7);
  double t13 = -pdPi*t11*t5 - t12;
  double t14 = pdSigma*t5 - t2;
  double t15 = t14*t8*x*y*z;
  double t16 = t8*(pdPi*(t0 + t1 - t3) + t3*t6);
  double t17 = t9*y;
  double t18 = t8*(pdPi*(t0 + t4) + t1*t6);
  double t19 = t9*z;
  double t20 = t8*(pdPi*(-t0 + t7) + t0*t6);
  H[0] = t10*(t2*(t0 + 2*t1) + t4*t6);
  H[1] = t10*t13;
  H[2] = t15;
  H[3] = t16*z;
  H[4] = t16*y;
  H[5] = t17*(pdSigma*t4*t5 - t2*(t0 + 2*t3));
  H[6] = t13*t17;
  H[7] = t18*z;
  H[8] = t15;
  H[9] = t18*x;
  H[10] = t14*t19*t4;
  H[11] = t19*(-t12 + t2*t5*t7);
  H[12] = t20*y;
  H[13] = t20*x;
  H[14] = t15;
}

