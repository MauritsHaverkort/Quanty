#define CifVacuumMargin   15.0  /* Angstrom added on each side of the atoms' extent along a non-periodic direction */
#define CifVacuumMinimum  20.0  /* Angstrom, minimum length of a vacuum-padded lattice vector */


/* Cartesian atom extent along dir (in Angstrom), padded to a usable
 * vacuum cell length. */
static double VacuumLengthAlongDirection(uint32_t NAtoms, const double *CartPos, const double dir[3])
{
  double vmin=INFINITY, vmax=-INFINITY, VacLen;
  uint32_t k;
  for(k=0;k<NAtoms;k++)
  {
    double proj = dir[0]*CartPos[3*k+0]+dir[1]*CartPos[3*k+1]+dir[2]*CartPos[3*k+2];
    if(proj<vmin) vmin=proj;
    if(proj>vmax) vmax=proj;
  }
  VacLen = (NAtoms>0 ? (vmax-vmin) : 0.0) + 2.0*CifVacuumMargin;
  if(VacLen<CifVacuumMinimum) VacLen=CifVacuumMinimum;
  return VacLen;
}



/* Appends Cell's CIF representation to *Cif, which must already be a
 * valid (possibly non-empty) DynamicString.
 */
int CrystalStructureTypeAddToCif(CrystalStructureType *Cell, DynamicString *Cif)
{
  int i,j,Finite[3],NFinite=0,PositionsAreFractional;
  double LengthConv,M[3][3],Minv[3][3];
  double *CartPos;
  uint32_t a;

  if(Cell==NULL) return 1;
  if(Cell->NAtoms>0 && Cell->Atom==NULL) return 1;

  for(i=0;i<3;i++)
  {
    Finite[i] = isfinite(Cell->rUnitCell[i][0]) && isfinite(Cell->rUnitCell[i][1]) && isfinite(Cell->rUnitCell[i][2]);
    if(Finite[i]) NFinite++;
  }

  if((Cell->Units&6)==0)      LengthConv = 1.0;           /* Angstrom */
  else if((Cell->Units&6)==2) { GetPhysicalConstant("a0",&LengthConv); LengthConv *= 1E10;} /* Bohr/a0 -> Angstrom */
  else if((Cell->Units&6)==4) LengthConv = 10.0;          /* nm -> Angstrom */
  else
  {
    fprintf(stderr,"CrystalStructureTypeAddToCif: undefined length-unit code (Units&6)==6\n");
    return 1;
  }

  PositionsAreFractional = ((Cell->Units&8)==8);
  if(PositionsAreFractional && NFinite<3)
  {
    fprintf(stderr,"CrystalStructureTypeAddToCif: relative atom positions (Units&8) require all three rUnitCell vectors to be finite\n");
    return 1;
  }

  /* Cartesian atom positions in Angstrom -- always from the original
   * rUnitCell, never the vacuum-padded one built below. */
  CartPos = (double *) malloc(sizeof(double)*3*(Cell->NAtoms>0?Cell->NAtoms:1));
  if(CartPos==NULL) return 1;
  for(a=0;a<Cell->NAtoms;a++)
  {
    if(PositionsAreFractional)
      for(j=0;j<3;j++)
        CartPos[3*a+j] = LengthConv*( Cell->Atom[a].Position[0]*Cell->rUnitCell[0][j]
                                     + Cell->Atom[a].Position[1]*Cell->rUnitCell[1][j]
                                     + Cell->Atom[a].Position[2]*Cell->rUnitCell[2][j] );
    else
      for(j=0;j<3;j++)
        CartPos[3*a+j] = LengthConv*Cell->Atom[a].Position[j];
  }

  for(i=0;i<3;i++)
    if(Finite[i])
      for(j=0;j<3;j++)
        M[i][j] = LengthConv*Cell->rUnitCell[i][j];

  if(NFinite==2)
  {
    for(i=0;i<3 && Finite[i];i++);            /* i = the one non-periodic vector */
    int m=(i+1)%3, n=(i+2)%3;
    double normal[3];
    Cross(M[m],M[n],normal);
    if(NormalizeVector(normal,1E-12))
    {
      fprintf(stderr,"CrystalStructureTypeAddToCif: the two periodic lattice vectors are parallel\n");
      free(CartPos); return 1;
    }
    for(j=0;j<3;j++) M[i][j] = VacuumLengthAlongDirection(Cell->NAtoms,CartPos,normal)*normal[j];
  }
  else if(NFinite==1)
  {
    for(i=0;i<3 && !Finite[i];i++);           /* i = the one periodic vector */
    double dir[3]={M[i][0],M[i][1],M[i][2]}, seed[3]={1.0,0.0,0.0}, u1[3],u2[3];
    if(NormalizeVector(dir, 1E-12))
    {
      fprintf(stderr,"CrystalStructureTypeAddToCif: the single periodic lattice vector has zero length\n");
      free(CartPos); return 1;
    }
    if(fabs(Dot(dir,seed))>0.9) { seed[0]=0.0; seed[1]=1.0; seed[2]=0.0; }
    Cross(dir,seed,u1); NormalizeVector(u1,1E-12);
    Cross(dir,u1,u2);   NormalizeVector(u2,1E-12);
    double *U[2]={u1,u2}; int idx=0;
    for(j=0;j<3;j++)
    {
      if(j==i) continue;
      for(int k=0;k<3;k++) M[j][k] = VacuumLengthAlongDirection(Cell->NAtoms,CartPos,U[idx])*U[idx][k];
      idx++;
    }
  }
  else if(NFinite==0)
  {
    double axis[3][3]={{1,0,0},{0,1,0},{0,0,1}};
    for(i=0;i<3;i++)
      for(j=0;j<3;j++)
        M[i][j] = VacuumLengthAlongDirection(Cell->NAtoms,CartPos,axis[i])*axis[i][j];
  }

  if(Invert3x3(M,Minv))
  {
    fprintf(stderr,"CrystalStructureTypeAddToCif: degenerate unit cell\n");
    free(CartPos); return 1;
  }

  double a_,b_,c_,alpha,beta,gamma;
  a_=Norm(M[0]); b_=Norm(M[1]); c_=Norm(M[2]);
  alpha=AngleBetweenVectors(M[1],M[2])*180/Pi;
  beta =AngleBetweenVectors(M[0],M[2])*180/Pi;
  gamma=AngleBetweenVectors(M[0],M[1])*180/Pi;

  sprintfAdd(Cif,"# Generated by Quanty, space group P1\n");
  if(NFinite<3)
    sprintfAdd(Cif,"# Original structure is %s; non-periodic direction(s) padded with vacuum\n",
               NFinite==2?"a 2D slab":NFinite==1?"a 1D chain":"a molecule (0D)");
  sprintfAdd(Cif,"data_Quanty\n");
  sprintfAdd(Cif,"_cell_length_a    %.6f\n",a_);
  sprintfAdd(Cif,"_cell_length_b    %.6f\n",b_);
  sprintfAdd(Cif,"_cell_length_c    %.6f\n",c_);
  sprintfAdd(Cif,"_cell_angle_alpha %.4f\n",alpha);
  sprintfAdd(Cif,"_cell_angle_beta  %.4f\n",beta);
  sprintfAdd(Cif,"_cell_angle_gamma %.4f\n",gamma);
  sprintfAdd(Cif,"_symmetry_space_group_name_H-M 'P 1'\n");
  sprintfAdd(Cif,"_symmetry_Int_Tables_number 1\n");
  sprintfAdd(Cif,"loop_\n_symmetry_equiv_pos_as_xyz\n'x, y, z'\n");
  sprintfAdd(Cif,"loop_\n_atom_site_label\n_atom_site_type_symbol\n_atom_site_fract_x\n_atom_site_fract_y\n_atom_site_fract_z\n_atom_site_occupancy\n");

  char **UsedLabel = (char **) malloc(sizeof(char*)*(Cell->NAtoms>0?Cell->NAtoms:1));
  for(a=0;a<Cell->NAtoms;a++)
  {
    double f[3];
    for(i=0;i<3;i++)
    {
      f[i] = Minv[0][i]*CartPos[3*a+0]+Minv[1][i]*CartPos[3*a+1]+Minv[2][i]*CartPos[3*a+2];
      f[i] -= floor(f[i]);
    }
    const char *base = (Cell->Atom[a].Name[0]!='\0') ? Cell->Atom[a].Name : AtomNumberToName(Cell->Atom[a].AtomNumber);
    char label[MAXStrLength];
    snprintf(label,MAXStrLength,"%s",base);
    for(j=0;j<(int)a;j++)
    {
      if(strcmp(UsedLabel[j],label)==0)
      {
        snprintf(label,MAXStrLength,"%s_%u",base,a+1);
        break;
      }
    }
    UsedLabel[a] = (char *) malloc(strlen(label)+1);
    strcpy(UsedLabel[a],label);
    sprintfAdd(Cif,"%s %s %.6f %.6f %.6f 1.0000\n", label, AtomNumberToName(Cell->Atom[a].AtomNumber), f[0], f[1], f[2]);
  }
  for(a=0;a<Cell->NAtoms;a++) free(UsedLabel[a]);
  free(UsedLabel);
  free(CartPos);
  return 0;
}

/* Initializes *Cif, then writes Cell into it. */
int CrystalStructureTypeToCif(CrystalStructureType *Cell, DynamicString *Cif)
{
  if(Cif==NULL) return 1;
  *Cif = InitDynamicString();
  return CrystalStructureTypeAddToCif(Cell, Cif);
}

/* Convenience overload: caller owns the buffer, free()s it.
 */
int CrystalStructureTypeToCif(CrystalStructureType *Cell, char **Cif)
{
  DynamicString Buff;
  int ret = CrystalStructureTypeToCif(Cell, &Buff);
  if(ret) { FreeDynamicString(&Buff); *Cif=NULL; return ret; }
  *Cif = Buff.str;
  return 0;
}
